import assert from 'node:assert/strict';

const store = new Map();
globalThis.chrome = { storage: { local: { async get(key) { return { [key]: store.get(key) }; }, async set(values) { Object.entries(values).forEach(([key, value]) => store.set(key, value)); } } } };
const { DEFAULT_FEATURE_FLAGS, getFeatureFlags, getNewTabCustomUrl, isFeatureEnabled, getNewTabDestination, getNewTabSearchEngine, getNewTabSearchUrl, normalizeNewTabCustomUrl, getPomodoroMinutes, getQuickLinks, getSettings, saveSettings } = await import('../shared/constants.js');
assert.equal(getPomodoroMinutes({ pomodoroMinutes: 2 }), 5);
assert.equal(getPomodoroMinutes({ pomodoroMinutes: 150 }), 120);
assert.equal(getPomodoroMinutes({ pomodoroMinutes: 34.7 }), 35);
assert.equal(getNewTabDestination({}), 'dashboard');
assert.equal(getNewTabDestination({ newTabDestination: 'native' }), 'native');
assert.equal(getNewTabDestination({ newTabDestination: 'custom' }), 'custom');
assert.equal(getNewTabDestination({ newTabDestination: 'invalide' }), 'dashboard');
assert.equal(getNewTabSearchEngine({ newTabSearchEngine: 'qwant' }), 'qwant');
assert.equal(getNewTabSearchEngine({ newTabSearchEngine: 'invalide' }), 'google');
assert.equal(getNewTabSearchUrl({ newTabSearchEngine: 'brave' }), 'https://search.brave.com/');
assert.equal(getNewTabSearchUrl({ newTabSearchEngine: 'startpage' }), 'https://www.startpage.com/');
assert.equal(normalizeNewTabCustomUrl('https://dashboard.example.test/app'), 'https://dashboard.example.test/app');
assert.equal(normalizeNewTabCustomUrl('http://localhost:3000'), 'http://localhost:3000/');
assert.equal(normalizeNewTabCustomUrl('javascript:alert(1)'), '');
assert.equal(normalizeNewTabCustomUrl('http://example.test'), '');
assert.equal(getNewTabCustomUrl({ newTabCustomUrl: 'https://example.test/' }), 'https://example.test/');
assert.equal(isFeatureEnabled({}, 'web.summary'), true);
assert.equal(isFeatureEnabled({ featureFlags: { 'web.summary': false } }, 'web.summary'), false);
assert.equal(getFeatureFlags({ featureFlags: { inconnue: false } }).inconnue, undefined);
assert.equal(getQuickLinks({ quickLinks: [] }).length, 0);
assert.equal(getQuickLinks({ quickLinks: [{ label: 'Invalide', url: 'javascript:alert(1)' }] }).length, 0);
await saveSettings({ pomodoroMinutes: 200, quickLinks: [], newTabDestination: 'custom', newTabSearchEngine: 'startpage', newTabCustomUrl: 'https://dashboard.example.test/app', featureFlags: { ...DEFAULT_FEATURE_FLAGS, 'media.inspect': false } });
const settings = await getSettings();
assert.equal(settings.pomodoroMinutes, 120);
assert.deepEqual(settings.quickLinks, []);
assert.equal(settings.newTabDestination, 'custom');
assert.equal(settings.newTabSearchEngine, 'startpage');
assert.equal(settings.newTabCustomUrl, 'https://dashboard.example.test/app');
assert.equal(settings.featureFlags['media.inspect'], false);
assert.equal(settings.featureFlags['web.summary'], true);
console.log('constants preferences simulation: ok');
